/* DSH 一键重启：面板只负责写脚本并拉起它，真正的“杀进程 / 重新启动”放在独立 PowerShell 里，
   这样杀死 DSH 的时候不会连带把面板自己带走。
   2026-11-09：加了全过程追踪（等待脚本 → 关旧进程 → 新进程 → 界面端口就绪），
   控制台据此显示“成功 / 失败 / 卡在哪一步”，不再只靠猜。 */
import fs from 'node:fs'
import path from 'node:path'
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { DSH_EXE, NODE, SURF } from './paths.js'
import { logLine, readJson, run } from './util.js'

const STATE_DIR = path.join(SURF, 'state')
const STATE_FILE = path.join(STATE_DIR, 'dsh-restart.json')
const LOG_FILE = path.join(STATE_DIR, 'dsh-restart.log')
const SCRIPT_FILE = path.join(STATE_DIR, 'restart-dsh.ps1')
// 面板自己的目录（解包后是 stellar-manager/lib），用来定位 cookie-guard.js
const LIB_DIR = path.dirname(fileURLToPath(import.meta.url))
const GUARD_SCRIPT = path.join(LIB_DIR, 'cookie-guard.js')
const MIN_GAP_MS = 25 * 1000          // 连点保护：正在重启时 25 秒内不再受理
const RECENT_MS = 10 * 60 * 1000      // 最近 10 分钟的结果算“这次”
const DONE_KEEP_MS = 10 * 60 * 1000
const POLL_MS = 1500

export function dshAvailable() {
  try { return fs.existsSync(DSH_EXE) } catch { return false }
}

// ── 状态文件 ────────────────────────────────────────────────
function writeState(next) {
  try {
    fs.mkdirSync(STATE_DIR, { recursive: true })
    fs.writeFileSync(STATE_FILE, JSON.stringify(next, null, 2), 'utf8')
    return next
  } catch { return next }
}

function patchState(mut) {
  const st = readJson(STATE_FILE, null) || {}
  if (!st || !st.at) return null
  const next = { ...st, ...mut }
  return writeState(next)
}

function step(key, text) {
  const st = readJson(STATE_FILE, null)
  if (!st || !st.at) return
  const steps = Array.isArray(st.steps) ? st.steps.slice() : []
  if (steps.some((s) => s.key === key)) return
  steps.push({ key, t: Date.now(), text })
  writeState({ ...st, steps })
}

export function readRestartState() {
  const st = readJson(STATE_FILE, null)
  if (!st || !st.at) return { phase: 'idle', at: '', by: '', ageMs: 0, steps: [] }
  const at = Number(st.at)
  const ageMs = Date.now() - at
  const steps = Array.isArray(st.steps) ? st.steps : []
  let phase = String(st.phase || 'requested')
  const legacy = !Array.isArray(st.steps)
  // 面板被打断（例如它自己刚刚重启）时，用时间兜个底：老记录不说成功也不说失败，
  // 由控制台的恢复逻辑去核对现在的进程，别凭时间瞎判。
  if ((phase === 'requested' || phase === 'stopping' || phase === 'stopped' || phase === 'launched')
    && (legacy || ageMs > 3 * 60 * 1000)) {
    phase = 'unknown'
  }
  const finishedAt = Number(st.finishedAt || 0)
  return {
    phase,
    at: new Date(at).toISOString(),
    by: String(st.by || ''),
    ageMs,
    method: String(st.method || ''),
    problems: Array.isArray(st.problems) ? st.problems : [],
    ok: phase === 'ok',
    failed: phase === 'fail',
    reason: String(st.reason || ''),
    bare: !!st.bare,
    port: Number(st.port || 0),
    url: String(st.url || ''),
    pid: Number(st.pid || 0),
    steps,
    durationMs: finishedAt ? finishedAt - at : 0,
    legacy: !!st.legacy || (steps.length === 1 && steps[0].key === 'legacy'),
    note: String(st.note || ''),
    reconciled: !!st.reconciled,
    recent: ageMs < DONE_KEEP_MS,
  }
}

export function readRestartLog(lines = 40) {
  try {
    const text = fs.readFileSync(LOG_FILE, 'utf8')
    return text.split('\n').slice(-lines).join('\n')
  } catch { return '' }
}

// 把任意路径变成「纯 ASCII 的 PowerShell 单引号字面量」：非 ASCII 字符用 [char]0xNNNN 拼，
// 因为脚本是以 ascii/utf8 落盘再交给 powershell.exe 5.1 执行的，中文路径直接写进去会乱码。
function psAscii(text) {
  const parts = []
  let buf = ''
  for (const ch of String(text)) {
    if (ch.charCodeAt(0) < 128) { buf += ch; continue }
    if (buf) { parts.push("'" + buf.replace(/'/g, "''") + "'"); buf = '' }
    parts.push('([char]0x' + ch.codePointAt(0).toString(16).toUpperCase().padStart(4, '0') + ')')
  }
  if (buf) { parts.push("'" + buf.replace(/'/g, "''") + "'") }
  return parts.length ? parts.join(' + ') : "''"
}

// ── 重启脚本 ────────────────────────────────────────────────
function scriptText() {
  const exe = psAscii(DSH_EXE)
  const workdir = psAscii(path.dirname(DSH_EXE))
  const log = psAscii(LOG_FILE)
  return [
    '# generated by Stellar panel',
    "$ErrorActionPreference = 'Continue'",
    "$log = " + log,
    "function W($m) { ('[' + (Get-Date).ToString('yyyy-MM-dd HH:mm:ss') + '] ' + $m) | Out-File -FilePath $log -Append -Encoding utf8 }",
    "W 'restart requested'",
    "Start-Sleep -Seconds 3",
    "$procs = @(Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue)",
    "W ('stopping ' + $procs.Count + ' process(es)')",
    "$procs | Stop-Process -Force -ErrorAction SilentlyContinue",
    "for ($i = 0; $i -lt 25; $i++) { if (@(Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue).Count -eq 0) { break }; Start-Sleep -Milliseconds 300 }",
    "Start-Sleep -Seconds 2",
    "# DSH just stopped: the Cookies db is free now, so trim the cookies that cause 431.",
    "$cg = " + psAscii(GUARD_SCRIPT),
    "if (Test-Path $cg) { try { $o = & " + psAscii(NODE) + " $cg 2>&1 | Out-String; W ('cookie guard exit=' + $LASTEXITCODE) } catch { W ('cookie guard failed: ' + $_.Exception.Message) } }",
    "if (Test-Path " + exe + ") {",
    "  Start-Process -FilePath " + exe + " -WorkingDirectory " + workdir,
    "  W 'launched'",
    "} else {",
    "  W 'exe missing'",
    "}",
    "Start-Sleep -Seconds 8",
    "$n = @(Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue).Count",
    "if ($n -eq 0) { W 'retry launch'; Start-Process -FilePath " + exe + " -WorkingDirectory " + workdir + "; Start-Sleep -Seconds 8 }",
    "W ('after launch processes=' + @(Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue).Count)",
    '',
  ].join('\n')
}

const TASK_NAME = 'Stellar Restart DSH'

function taskClock() {
  const t = new Date(Date.now() + 5 * 60 * 1000)
  return String(t.getHours()).padStart(2, '0') + ':' + String(t.getMinutes()).padStart(2, '0')
}

const TASK_SETTINGS = "$s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable; Set-ScheduledTask -TaskName '" + TASK_NAME + "' -Settings $s | Out-Null"
let taskWarning = ''

async function launchViaTask(delayMs = 0) {
  taskWarning = ''
  let file = SCRIPT_FILE
  if (delayMs > 0) {
    // 延迟执行：套一层等待，别让正在看页面的人被突然掐断
    file = path.join(STATE_DIR, 'restart-dsh-delayed.ps1')
    const secs = Math.round(delayMs / 1000)
    try {
      fs.writeFileSync(file, ['# generated by Stellar panel (delayed)', "Start-Sleep -Seconds " + secs, '& (' + psAscii(SCRIPT_FILE) + ')'].join('\n'), 'utf8')
    } catch { file = SCRIPT_FILE }
  }
  const tr = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "' + file + '"'
  const created = await run('schtasks.exe', ['/create', '/tn', TASK_NAME, '/tr', tr, '/sc', 'once', '/st', taskClock(), '/f'], { timeoutMs: 30000 })
  if (created.code !== 0) return 'create: ' + String(created.err || created.out || '').trim().slice(0, 200)
  // schtasks 默认带「用电池时不启动」(DisallowStartIfOnBatteries=true)。笔记本一拔电，
  // 任务就永远停在 Queued：2026-11-09 00:16 主人点按钮没反应就是这个原因（当时电池供电）。
  const fixed = await run('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', TASK_SETTINGS], { timeoutMs: 30000 })
  if (fixed.code !== 0) taskWarning = 'battery-settings: ' + String(fixed.err || fixed.out || '').trim().slice(0, 120)
  const started = await run('schtasks.exe', ['/run', '/tn', TASK_NAME], { timeoutMs: 30000 })
  if (started.code !== 0) return 'run: ' + String(started.err || started.out || '').trim().slice(0, 200)
  // 任务只是启动器，启动完就删，别在任务计划里留垃圾
  setTimeout(() => { run('schtasks.exe', ['/delete', '/tn', TASK_NAME, '/f'], { timeoutMs: 20000 }) }, 3000)
  return ''
}

async function launchViaWmi(file = SCRIPT_FILE) {
  const cmd = "$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{CommandLine='powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"" + file + "\"'}; if ($r.ReturnValue -eq 0) { 'ok' } else { 'fail ' + $r.ReturnValue }"
  const res = await run('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', cmd], { timeoutMs: 20000 })
  if (String(res.out || '').trim() === 'ok') return ''
  return 'wmi: ' + String(res.err || res.out || '').trim().slice(0, 200)
}

// ── 进程 / 端口观察 ─────────────────────────────────────────
const SNAP_PS = [
  "$ps = @(Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue)",
  '$parts = foreach ($p in $ps) {',
  '  $ports = @(Get-NetTCPConnection -State Listen -OwningProcess $p.Id -ErrorAction SilentlyContinue | Select-Object -ExpandProperty LocalPort -Unique)',
  "  $p.Id.ToString() + '|' + ($ports -join ',')",
  '}',
  '$parts',
].join('\n')

async function dshSnapshot() {
  try {
    const r = await run('powershell.exe', ['-NoProfile', '-Command', SNAP_PS], { timeoutMs: 20000 })
    const items = []
    for (const line of String(r.out || '').split(/\r?\n/)) {
      const m = /^\s*(\d+)\|(.*)$/.exec(line)
      if (!m) continue
      const ports = String(m[2] || '').split(',').map((x) => Number(x.trim())).filter((n) => n > 0 && n < 65536)
      items.push({ pid: Number(m[1]), ports })
    }
    return items
  } catch { return [] }
}

async function probeHttp(ports) {
  for (const port of ports) {
    try {
      const res = await fetch('http://127.0.0.1:' + port + '/', { signal: AbortSignal.timeout(1500) })
      if (res.status < 500) return port
    } catch {}
  }
  return 0
}

let pollTimer = null
let pollBusy = false
let pollStop = false

function stopPolling() {
  pollStop = true
  if (pollTimer) { clearInterval(pollTimer); pollTimer = null }
}

async function tick() {
  if (pollBusy) return
  pollBusy = true
  try {
    const st = readJson(STATE_FILE, null)
    if (!st || !st.at) return stopPolling()
    if (st.phase === 'ok' || st.phase === 'fail') return stopPolling()
    const now = Date.now()
    const executeAt = Number(st.executeAt || st.at)
    const startedAt = Math.max(Number(st.at), executeAt)
    const elapsed = now - startedAt
    if (now < executeAt) {
      step('queued', '已排定 ' + new Date(executeAt).toLocaleTimeString() + ' 执行，等它到点')
      return
    }
    const before = (Array.isArray(st.beforePids) ? st.beforePids : []).map(Number)
    const snap = await dshSnapshot()
    const pids = snap.map((s) => s.pid)
    const oldAlive = before.filter((pid) => pids.includes(pid))
    const fresh = snap.filter((s) => !before.includes(s.pid))

    if (!Array.isArray(st.steps) || st.phase === 'unknown') {
      const allPorts = snap.reduce((acc, s) => acc.concat(s.ports), [])
      if (!snap.length) return fail('这是旧版本留下的重启记录，没有步骤可查；现在 DSH 也没在运行，双击桌面图标重新打开它。')
      const port = await probeHttp(allPorts)
      if (!port) return fail('旧版本留下的重启记录，DSH 进程在跑但界面端口没响应；建议再点一次「重启 DSH」看完整过程。')
      const owner = snap.find((s) => s.ports.includes(port)) || snap[0]
      step('legacy', '旧版本没记步骤，按现状补全：DSH 在跑，界面 http://127.0.0.1:' + port)
      return succeed(owner.pid, port, 'http://127.0.0.1:' + port, { legacy: true })
    }

    if (st.phase === 'requested') {
      const logText = readRestartLog(12)
      const marker = logText.split('\n').filter((l) => l.includes('restart requested')).pop() || ''
      const mt = /\[(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\]/.exec(marker)
      const logAt = mt ? new Date(mt[1].replace(' ', 'T')).getTime() : 0
      if (logAt && logAt >= Number(st.at) - 5000) {
        step('stopping', '重启脚本已接手（' + mt[1] + '），准备关掉 DSH')
        patchState({ phase: 'stopping' })
      } else if (now - Math.max(Number(st.at), executeAt) > 30000) {
        step('fail', '点了 30 秒，重启脚本还没执行')
        return fail('重启脚本没被执行（计划任务可能被系统拦下：电池、权限或杀软）。日志里也没有新记录。')
      }
    }

    if (oldAlive.length === 0 && before.length > 0) {
      step('stopped', '旧进程已全部退出' + (st.stoppedAt ? '' : ''))
      if (!st.stoppedAt) patchState({ phase: 'stopped', stoppedAt: now })
    }

    if (fresh.length) {
      const first = fresh[0]
      if (!st.pid) {
        patchState({ phase: 'launched', pid: first.pid, launchedAt: now })
        step('launched', '新进程已启动 pid ' + first.pid)
      }
      const ports = fresh.reduce((acc, s) => acc.concat(s.ports), [])
      const port = await probeHttp(ports)
      if (port) {
        const url = 'http://127.0.0.1:' + port
        const owner = fresh.find((s) => s.ports.includes(port)) || first
        step('ready', '界面已就绪：' + url + '（用时 ' + Math.round((now - Number(st.at)) / 1000) + ' 秒）')
        return succeed(owner.pid, port, url)
      }
      const launchedAt = Number(st.launchedAt || now)
      if (now - launchedAt > 45000) return fail('新进程起来了（pid ' + first.pid + '），但界面端口一直没响应，可能卡在启动。')
    } else if (oldAlive.length === 0 && elapsed > 75000) {
      return fail('DSH 关掉了，但 75 秒内没再起来（脚本日志：' + (readRestartLog(3).split('\n').filter(Boolean).pop() || '空') + '）')
    }

    if (oldAlive.length && elapsed > 45000) {
      return fail('45 秒了 DSH 旧进程还在运行，这次重启没生效（脚本日志：' + (readRestartLog(2).split('\n').filter(Boolean).pop() || '空') + '）')
    }
    if (elapsed > 150000) return fail('超过 2 分半还没走完重启流程，先当作失败。')
  } catch (error) {
    logLine('dsh restart poll error ' + (error && error.message || error))
  } finally {
    pollBusy = false
  }
}

function succeed(pid, port, url, extra = {}) {
  const st = readJson(STATE_FILE, null) || {}
  writeState({ ...st, phase: 'ok', pid, port, url, finishedAt: Date.now(), reason: '', ...extra })
  stopPolling()
  logLine('dsh restart ok (pid ' + pid + ', ' + url + ')')
}

function fail(reason) {
  const st = readJson(STATE_FILE, null) || {}
  step('fail', reason)
  writeState({ ...st, phase: 'fail', reason, finishedAt: Date.now(), failed: true, failedAt: Date.now() })
  stopPolling()
  logLine('dsh restart failed: ' + reason)
}

function startPolling() {
  if (pollTimer) return
  pollStop = false
  pollTimer = setInterval(() => { if (pollStop) return stopPolling(); tick() }, POLL_MS)
  if (pollTimer.unref) pollTimer.unref()
  tick()
}

// 面板自己重启（改代码 / 守护拉起）后，接着盯没走完的那次重启
export function resumeRestartPolling() {
  const st = readJson(STATE_FILE, null)
  if (!st || !st.at) return
  if (st.phase === 'ok' || st.phase === 'fail') return
  if (Date.now() - Number(st.at) > 10 * 60 * 1000) return
  startPolling()
}

// 面板启动时纠正误判：记录说失败，但 DSH 明确在跑，就补记为成功
export async function reconcileRestartState() {
  const st = readJson(STATE_FILE, null)
  if (!st || st.phase !== 'fail') return
  const finished = Number(st.finishedAt || st.at)
  if (Date.now() - finished > 6 * 60 * 60 * 1000) return
  const why = String(st.reason || '')
  const timedOut = ['旧进程还在运行', '界面端口一直没响应', '超过 2 分半'].some((k) => why.includes(k))
  if (!timedOut) return
  try {
    const snap = await dshSnapshot()
    if (!snap.length) return
    const allPorts = snap.reduce((acc, s) => acc.concat(s.ports), [])
    const port = await probeHttp(allPorts)
    if (!port) return
    const owner = snap.find((s) => s.ports.includes(port)) || snap[0]
    const url = 'http://127.0.0.1:' + port
    writeState({ ...st, phase: 'ok', pid: owner.pid, port, url, failed: false, failedAt: 0, reason: '', finishedAt: Date.now(), reconciled: true, note: '上一次被判为失败，复查发现 DSH 已在运行，已补记为成功' })
    step('fixed', '复查：DSH 现在在运行 ' + url + '，上一次的失败判定是误判，已改记为成功')
    logLine('dsh restart reconciled: running at ' + url)
  } catch (error) {
    logLine('dsh restart reconcile error ' + (error && error.message || error))
  }
}

// ── 对外：发起重启 ─────────────────────────────────────────
export async function restartDsh(by = 'panel', opts = {}) {
  if (!dshAvailable()) return { ok: false, message: '找不到 DSH 程序：' + DSH_EXE }
  const delayMs = Math.max(0, Math.min(120000, Number(opts.delayMs) || 0))
  const prev = readRestartState()
  if (prev.phase === 'requested' || prev.phase === 'stopping' || prev.phase === 'stopped' || prev.phase === 'launched') {
    if (prev.ageMs < MIN_GAP_MS) {
      return { ok: false, message: '这次重启还在进行中（' + new Date(prev.at).toLocaleTimeString() + ' 点的），别重复点，约 20–40 秒回来。' }
    }
  }
  if (prev.phase === 'ok' && prev.ageMs < 90 * 1000) {
    return { ok: false, message: '刚刚已经重启成功了（' + new Date(prev.at).toLocaleTimeString() + ' 点，用时 ' + Math.round(prev.durationMs / 1000) + ' 秒，新界面 ' + prev.url + '），不用再点。' }
  }

  const at = Date.now()
  try {
    fs.mkdirSync(STATE_DIR, { recursive: true })
    fs.writeFileSync(SCRIPT_FILE, scriptText(), 'utf8')
  } catch (error) {
    return { ok: false, message: '写重启脚本失败：' + (error && error.message || error) }
  }

  // 首选计划任务：它在 DSH 之外启动，DSH 被杀时脚本不会被一起带走；其次是 WMI，最后才退回 detached spawn
  const snap = await dshSnapshot()
  const beforePids = snap.map((s) => s.pid)
  const problems = []
  writeState({
    at,
    by,
    exe: DSH_EXE,
    method: 'pending',
    problems,
    beforePids,
    phase: 'requested',
    executeAt: at + delayMs,
    steps: [{ key: 'request', t: at, text: '收到重启请求（' + by + '）' + (delayMs ? '，' + Math.round(delayMs / 1000) + ' 秒后执行' : '') }],
  })

  let method = 'task'
  let why = await launchViaTask(delayMs)
  if (why) {
    problems.push(why)
    method = 'wmi'
    why = await launchViaWmi(delayMs > 0 && fs.existsSync(path.join(STATE_DIR, 'restart-dsh-delayed.ps1')) ? path.join(STATE_DIR, 'restart-dsh-delayed.ps1') : SCRIPT_FILE)
    if (why) {
      problems.push(why)
      method = 'spawn'
      const file = delayMs > 0 && fs.existsSync(path.join(STATE_DIR, 'restart-dsh-delayed.ps1')) ? path.join(STATE_DIR, 'restart-dsh-delayed.ps1') : SCRIPT_FILE
      try {
        const child = spawn('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', file], { detached: true, stdio: 'ignore', windowsHide: true })
        child.unref()
      } catch (error) {
        fail('拉起重启脚本失败：' + (error && error.message || error))
        return { ok: false, message: '拉起重启脚本失败：' + (error && error.message || error) }
      }
    }
  }
  if (taskWarning) problems.push(taskWarning)
  patchState({ method, problems })
  startPolling()
  logLine('dsh restart requested by ' + by + ' via ' + method + (delayMs ? ' (delay ' + Math.round(delayMs / 1000) + 's)' : '') + (problems.length ? ' (' + problems.join(' | ') + ')' : ''))
  const head = delayMs ? Math.round(delayMs / 1000) + ' 秒后' : '大约 10 秒内'
  return {
    ok: true,
    at,
    method,
    message: '已排定重启：' + head + '关掉 DSH，20–40 秒回来。控制台会实时显示走到哪一步（等待脚本 → 关闭旧进程 → 新进程 → 界面就绪）。面板、SnowLuma、桥接不受影响。',
  }
}
